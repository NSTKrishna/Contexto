#[cfg(test)]
mod tests {
    use super::*;
    use crate::{ContextEvent, EventSource, Task, TaskStatus};

    fn make_task(name: &str, status: TaskStatus) -> Task {
        let mut t = Task::new(name);
        t.status = status;
        t
    }

    fn terminal_event(label: &str, content: &str) -> ContextEvent {
        ContextEvent::new(EventSource::Terminal, label, content)
    }

    fn manual_event(content: &str) -> ContextEvent {
        ContextEvent::new(EventSource::Manual, "note", content)
    }

    #[test]
    fn test_empty_events_produces_card() {
        let task = make_task("refactor auth", TaskStatus::Completed);
        let card = extract_session_card(&task, &[]);
        assert_eq!(card.goal, "refactor auth");
        assert!(card.files_touched.is_empty());
        assert!(card.commands_verified.is_empty());
        assert!(card.decisions.is_empty());
        assert_eq!(card.result, SessionResult::Completed);
    }

    #[test]
    fn test_abandoned_task_result() {
        let task = make_task("wip feature", TaskStatus::Abandoned);
        let card = extract_session_card(&task, &[]);
        assert_eq!(card.result, SessionResult::Abandoned);
    }

    #[test]
    fn test_file_path_extraction_from_content() {
        let task = make_task("fix auth", TaskStatus::Completed);
        let events = vec![terminal_event(
            "cargo check",
            "error in crates/ctxd/src/auth.rs:42\nwarning in Cargo.toml",
        )];
        let card = extract_session_card(&task, &events);
        assert!(
            card.files_touched.iter().any(|f| f.contains("auth.rs")),
            "auth.rs should be extracted, got: {:?}",
            card.files_touched
        );
        assert!(
            card.files_touched.iter().any(|f| f.contains("Cargo.toml")),
            "Cargo.toml should be extracted, got: {:?}",
            card.files_touched
        );
    }

    #[test]
    fn test_exit_code_from_metadata() {
        let task = make_task("run tests", TaskStatus::Completed);
        let mut event = terminal_event("cargo test", "running 5 tests\nok");
        event.metadata = Some(serde_json::json!({ "exit_code": 0 }));
        let card = extract_session_card(&task, &[event]);
        assert_eq!(card.commands_verified.len(), 1);
        assert_eq!(card.commands_verified[0].exit_code, Some(0));
    }

    #[test]
    fn test_exit_code_from_content_pattern() {
        let task = make_task("run tests", TaskStatus::Completed);
        let event = terminal_event("cargo test", "test result: FAILED\nexited with code 101");
        let card = extract_session_card(&task, &[event]);
        assert_eq!(card.commands_verified[0].exit_code, Some(101));
    }

    #[test]
    fn test_decisions_extracted_from_manual_events() {
        let task = make_task("design session", TaskStatus::Completed);
        let events = vec![
            manual_event("Use HMAC-SHA256 with 0600 token storage"),
            manual_event("Defer vector search to Phase 6"),
        ];
        let card = extract_session_card(&task, &events);
        assert_eq!(card.decisions.len(), 2);
        assert!(card.decisions[0].contains("HMAC-SHA256"));
        assert!(card.decisions[1].contains("Phase 6"));
    }

    #[test]
    fn test_duplicate_commands_deduped() {
        let task = make_task("iterative build", TaskStatus::Completed);
        let events = vec![
            terminal_event("cargo check", "ok"),
            terminal_event("cargo check", "ok"), // duplicate
            terminal_event("cargo test", "passed"),
        ];
        let card = extract_session_card(&task, &events);
        // "cargo check" should appear only once
        let cargo_check_count = card
            .commands_verified
            .iter()
            .filter(|c| c.cmd == "cargo check")
            .count();
        assert_eq!(cargo_check_count, 1);
    }

    #[test]
    fn test_token_estimate_reasonable() {
        let task = make_task("implement ring buffer", TaskStatus::Completed);
        let events = vec![
            terminal_event("cargo test", "ok"),
            manual_event("Use mpsc channel with 1000 capacity"),
        ];
        let card = extract_session_card(&task, &events);
        // Should be between 50 and 10,000 tokens for a small session
        assert!(card.token_estimate >= 50);
        assert!(card.token_estimate < 10_000);
    }

    #[test]
    fn test_target_dir_files_excluded() {
        let task = make_task("build", TaskStatus::Completed);
        let event = terminal_event(
            "cargo build",
            "Compiling target/debug/ctxd\nCompiling crates/ctxd/src/main.rs",
        );
        let card = extract_session_card(&task, &[event]);
        assert!(
            !card.files_touched.iter().any(|f| f.contains("target/")),
            "target/ paths should be excluded, got: {:?}",
            card.files_touched
        );
    }

    #[test]
    fn test_session_card_markdown_format() {
        let task = make_task("implement JWT auth", TaskStatus::Completed);
        let events = vec![
            terminal_event("cargo test -p ctxd", "test result: ok. 5 passed"),
            manual_event("Used HMAC-SHA256 signing"),
        ];
        let card = extract_session_card(&task, &events);
        let md = card.to_markdown();
        assert!(md.contains("implement JWT auth"));
        assert!(md.contains("Completed"));
        assert!(md.contains("HMAC-SHA256"));
    }

    #[test]
    fn test_session_card_json_roundtrip() {
        let task = make_task("roundtrip test", TaskStatus::Completed);
        let card = extract_session_card(&task, &[]);
        let json = card.to_json();
        let recovered = SessionCard::from_json(&json).expect("must deserialize");
        assert_eq!(recovered.goal, card.goal);
        assert_eq!(recovered.task_id, card.task_id);
    }
}
